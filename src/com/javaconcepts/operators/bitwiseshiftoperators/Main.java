package com.javaconcepts.operators.bitwiseshiftoperators;

public class Main {
    public static void main(String[] args) {
        int a = 4;

        // left shift operator
        System.out.println(a << 1);
        System.out.println(a << 2);

        // right shift operator
        System.out.println(a >> 1);
        System.out.println(a >> 2);
    }
}
