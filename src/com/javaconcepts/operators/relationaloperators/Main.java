package com.javaconcepts.operators.relationaloperators;

public class Main {
    public static void main(String[] args) {
        int a = 4;
        int b = 7;
        System.out.println("Is Equal: " + (a == b));
        System.out.println("Is Not Equal: " + (a != b));
        System.out.println("Is Greater Than: " + (a > b));
        System.out.println("Is Less Than: " + (a < b));
        System.out.println("Is Greater Than or Equal: " + (a >= b));
        System.out.println("Is Less Than or Equal: " + (a <= b));
    }
}
